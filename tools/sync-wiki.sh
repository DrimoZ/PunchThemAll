Use it in any modpack, public or private — no permission needed, credit never required.

This wiki is generated from [docs/]($BLOB/docs); edit there.
EOF

# Community is the one page with no counterpart in the repository, so it is left alone.
CHANGED=0
for generated in "$OUT_DIR"/*.md; do
    name="$(basename "$generated")"
    if ! cmp -s "$generated" "$WIKI/$name"; then
        CHANGED=1
        if [ "$CHECK_ONLY" = true ]; then
            echo "out of date: $name"
        else
            cp "$generated" "$WIKI/$name"
            echo "updated: $name"
        fi
    fi
done

if [ "$CHECK_ONLY" = true ]; then
    if [ "$CHANGED" -eq 1 ]; then
        echo "The wiki is behind the documentation. Run tools/sync-wiki.sh to regenerate it." >&2
        exit 1
    fi
    echo "The wiki matches the documentation."
    exit 0
fi

if [ "$CHANGED" -eq 0 ]; then
    echo "Already up to date."
else
    echo
    echo "Review and push:"
    echo "  git -C \"$WIKI\" diff"
    echo "  git -C \"$WIKI\" add -A && git -C \"$WIKI\" commit -m \"Sync wiki with docs\" && git -C \"$WIKI\" push"
fi
